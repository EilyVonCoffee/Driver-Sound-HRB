import 'package:flutter_test/flutter_test.dart';
import 'package:iem_driver/models/eq_band.dart';
import 'package:iem_driver/services/auto_eq_text_parser.dart';

void main() {
  const parser = AutoEqTextParser();

  test('parses AutoEQ directives and ignores comments and metadata', () {
    final preset = parser.parse('''
# AutoEQ export
Generated by community tool
Preamp: -4.5 dB
Filter 1: ON PK Fc 31 Hz Gain 2.0 dB Q 0.70
Filter 2: OFF HS Fc 9000 Hz Gain -1.25 dB Q 0.80
''');

    expect(preset.preampDb, -4.5);
    expect(preset.bands[0].enabled, isTrue);
    expect(preset.bands[0].frequencyHz, 31);
    expect(preset.bands[0].gainDb, 2);
    expect(preset.bands[0].q, 0.7);
    expect(preset.bands[1].enabled, isFalse);
    expect(preset.bands[1].type, EqFilterType.highShelf);
    expect(preset.bands[9].enabled, isFalse);
  });

  test('export and import round-trip preserves all filter types and values',
      () {
    final bands = List.generate(
      10,
      (index) => EqBand(
        enabled: index.isEven,
        type: EqFilterType.values[index % EqFilterType.values.length],
        frequencyHz: 30 + index * 700,
        gainDb: -12 + index * 1.5,
        q: 0.3 + index * 0.5,
      ),
    );
    final text = parser.encode(bands: bands, preampDb: -3.5);
    final result = parser.parse(text);

    expect(result.preampDb, -3.5);
    expect(result.bands, bands);
  });

  test('rejects duplicate, out-of-range and malformed filters', () {
    expect(
      () => parser.parse('Filter 1: ON PK Fc 31 Hz Gain 2 dB Q 0.7\n'
          'Filter 1: ON PK Fc 32 Hz Gain 1 dB Q 0.7'),
      throwsFormatException,
    );
    expect(
      () => parser.parse('Filter 11: ON PK Fc 31 Hz Gain 2 dB Q 0.7'),
      throwsFormatException,
    );
    expect(
      () => parser.parse('Filter 1: ON PK Fc 31 Hz Gain nope dB Q 0.7'),
      throwsFormatException,
    );
  });

  test('auto-preamp uses the sampled cascaded biquad response', () {
    final bands = List.generate(
      10,
      (index) => EqBand(
        enabled: index == 4,
        type: EqFilterType.peaking,
        frequencyHz: index == 4 ? 1000 : 20 + index * 1500,
        gainDb: index == 4 ? 5 : 0,
        q: 0.8,
      ),
    );

    expect(AutoEqTextParser.peakGainDb(bands), closeTo(5, 0.02));
    expect(AutoEqTextParser.recommendedPreampDb(bands), closeTo(-5, 0.02));
    expect(
      AutoEqTextParser.recommendedPreampDb(
        bands.map((band) => band.copyWith(enabled: false)).toList(),
      ),
      0,
    );
  });
}
